# Blog 06 - Step 1: Prepare the PSID parent-child income data.
# Parent income: 1998 earnings (1999 interview); child income: 2022 earnings (2023 interview).
# R packages: install.packages(c("here", "reticulate"))
# Python dependency, if needed: reticulate::py_install("pandas")

if (!requireNamespace("here", quietly = TRUE)) stop("Install R package: here")
if (!requireNamespace("reticulate", quietly = TRUE)) stop("Install R package: reticulate")

raw_dir <- here::here("blog", "posts", "post6", "data", "raw")
out_dir <- here::here("blog", "posts", "post6", "data", "processed")
if (!dir.exists(raw_dir)) stop("Missing data/raw. Open the website .Rproj first.")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

files <- c(pid = "PID23.txt", individual = "IND2023ER.txt",
           family1999 = "FAM1999ER.txt", family2023 = "FAM2023ER.txt")
paths <- stats::setNames(file.path(raw_dir, unname(files)), names(files))
missing <- paths[!file.exists(paths)]
if (length(missing)) stop("Missing raw data: ", paste(basename(missing), collapse = ", "))

# Input and output paths for Python.
python_paths <- paste(
  sprintf("pid_path = %s", encodeString(unname(paths[["pid"]]), quote = '"')),
  sprintf("ind_path = %s", encodeString(unname(paths[["individual"]]), quote = '"')),
  sprintf("family99_path = %s", encodeString(unname(paths[["family1999"]]), quote = '"')),
  sprintf("family23_path = %s", encodeString(unname(paths[["family2023"]]), quote = '"')),
  sprintf("output_csv = %s", encodeString(file.path(out_dir, "ige_single_year.csv"), quote = '"')),
  sep = "\n"
)

# Data extraction and matching.
python_code <- paste(c(
  "import re",
  "import sqlite3",
  "from pathlib import Path",
  "import pandas as pd",
  "",
  "# Fields used in this analysis.",
  "columns = {",
  "    'pid': ['PID1', 'PID2', 'PID3', 'PID4', 'PID5', 'PID23', 'PID24'],",
  "    'individual': ['ER30000', 'ER30001', 'ER30002',",
  "                   'ER33501', 'ER33502', 'ER33503', 'ER33504',",
  "                   'ER35101', 'ER35102', 'ER35103', 'ER35104'],",
  "    'family1999': ['ER13002', 'ER16463', 'ER16490', 'ER16465', 'ER16511'],",
  "    'family2023': ['ER82002', 'ER85496', 'ER85477', 'ER85524', 'ER85505']",
  "}",
  "",
  "",
  "def read_psid(filename, wanted):",
  "    path = Path(filename)",
  "    layout = path.with_suffix('.do')",
  "    if not path.is_file() or not layout.is_file():",
  "        raise FileNotFoundError(f'Need both {path.name} and {layout.name}')",
  "    print(f'Reading {path.name} ...')",
  "    do_text = layout.read_text(encoding='utf-8-sig', errors='replace')",
  "    do_text = re.sub(r'/\\*.*?\\*/', ' ', do_text, flags=re.S)",
  "    match = re.search(r'\\binfix\\b(.*?)\\busing\\b', do_text, re.I | re.S)",
  "    if match is None:",
  "        raise ValueError(f'No Stata infix layout found in {layout.name}')",
  "    # Layout positions can be ranges (12-18) or single columns (12).",
  "    positions = {}",
  "    for name, start, end in re.findall(",
  "            r'\\b([A-Za-z][A-Za-z0-9_]*)\\s+(\\d+)\\s*(?:-\\s*(\\d+))?\\b',",
  "            match.group(1)):",
  "        positions[name.upper()] = (int(start) - 1, int(end or start))",
  "    missing = sorted(set(wanted) - set(positions))",
  "    if missing:",
  "        raise ValueError(f'{layout.name} missing fields: {missing}')",
  "",
  "    values = {name: [] for name in wanted}",
  "    with path.open('rb') as stream:",
  "        for line in stream:",
  "            if not line.strip():",
  "                continue",
  "            for name in wanted:",
  "                a, b = positions[name]",
  "                values[name].append(line[a:b].strip().decode('ascii', 'replace'))",
  "    frame = pd.DataFrame(values)",
  "    for name in wanted:",
  "        frame[name] = pd.to_numeric(frame[name], errors='coerce')",
  "    return frame",
  "",
  "",
  "pid = read_psid(pid_path, columns['pid'])",
  "ind = read_psid(ind_path, columns['individual'])",
  "f99 = read_psid(family99_path, columns['family1999'])",
  "f23 = read_psid(family23_path, columns['family2023'])",
  "",
  "# Check that the PID and individual files use the same release.",
  "if (pid['PID1'].nunique() != 1 or ind['ER30000'].nunique() != 1 or",
  "        pid['PID1'].iloc[0] != ind['ER30000'].iloc[0]):",
  "    raise ValueError('PID23 and IND2023ER have incompatible release numbers')",
  "",
  "pid = pid.rename(columns={",
  "    'PID2': 'child_fam68', 'PID3': 'child_pn',",
  "    'PID4': 'mother_fam68', 'PID5': 'mother_pn',",
  "    'PID23': 'father_fam68', 'PID24': 'father_pn'",
  "})",
  "ind = ind.rename(columns={",
  "    'ER30001': 'fam68', 'ER30002': 'pn',",
  "    'ER33501': 'fam99', 'ER33502': 'seq99',",
  "    'ER33503': 'rel99', 'ER33504': 'age99',",
  "    'ER35101': 'fam23', 'ER35102': 'seq23',",
  "    'ER35103': 'rel23', 'ER35104': 'age23'",
  "})",
  "f99 = f99.rename(columns={",
  "    'ER13002': 'fam99', 'ER16463': 'head_labor98',",
  "    'ER16490': 'head_business98', 'ER16465': 'wife_labor98',",
  "    'ER16511': 'wife_business98'",
  "})",
  "f23 = f23.rename(columns={",
  "    'ER82002': 'fam23', 'ER85496': 'rp_labor22',",
  "    'ER85477': 'rp_business22', 'ER85524': 'sp_labor22',",
  "    'ER85505': 'sp_business22'",
  "})",
  "",
  "# Check for duplicate IDs before joining the tables.",
  "for label, frame, keys in [",
  "    ('PID23', pid, ['child_fam68', 'child_pn']),",
  "    ('IND2023ER', ind, ['fam68', 'pn']),",
  "    ('FAM1999ER', f99, ['fam99']),",
  "    ('FAM2023ER', f23, ['fam23'])",
  "]:",
  "    if frame.duplicated(keys).any():",
  "        raise ValueError(f'Duplicate identification key in {label}: {keys}')",
  "",
  "# Treat specified top-coded and invalid incomes as missing; keep zeros.",
  "limits99 = {",
  "    'head_labor98': 9999999, 'wife_labor98': 9999997,",
  "    'head_business98': 999999, 'wife_business98': 999999",
  "}",
  "for name, limit in limits99.items():",
  "    f99.loc[(f99[name] < 0) | (f99[name] >= limit), name] = float('nan')",
  "for name in ['rp_labor22', 'rp_business22', 'sp_labor22', 'sp_business22']:",
  "    f23.loc[(f23[name] < 0) | (f23[name] > 9999997), name] = float('nan')",
  "",
  "# Add wage and business labor income for each year.",
  "# Farm income is excluded because it also includes returns to assets.",
  "f99['head_income98'] = f99['head_labor98'] + f99['head_business98']",
  "f99['wife_income98'] = f99['wife_labor98'] + f99['wife_business98']",
  "f23['rp_income22'] = f23['rp_labor22'] + f23['rp_business22']",
  "f23['sp_income22'] = f23['sp_labor22'] + f23['sp_business22']",
  "",
  "# Match children to their biological parents by person ID.",
  "# Use family interview IDs to attach the 1999 and 2023 income records.",
  "# Sum income across the two matched parents.",
  "# The child need not live with either parent in 1999.",
  "query = '''",
  "WITH valid_pid AS (",
  "    SELECT child_fam68, child_pn, father_fam68, father_pn,",
  "           mother_fam68, mother_pn",
  "    FROM pid",
  "    WHERE child_fam68 > 0 AND child_pn BETWEEN 1 AND 399",
  "      AND father_fam68 > 0 AND father_pn BETWEEN 1 AND 399",
  "      AND mother_fam68 > 0 AND mother_pn BETWEEN 1 AND 399",
  "      AND NOT (father_fam68 = mother_fam68 AND father_pn = mother_pn)",
  "),",
  "linked AS (",
  "    SELECT p.*,",
  "           c.fam99 AS child_fam99, c.seq99 AS child_seq99,",
  "           c.age99 AS child_age99,",
  "           c.fam23 AS child_fam23, c.seq23 AS child_seq23,",
  "           c.rel23 AS child_rel23, c.age23 AS child_age23,",
  "           f.fam99 AS father_fam99, f.seq99 AS father_seq99,",
  "           f.rel99 AS father_rel99, f.age99 AS father_age99,",
  "           m.fam99 AS mother_fam99, m.seq99 AS mother_seq99,",
  "           m.rel99 AS mother_rel99, m.age99 AS mother_age99",
  "    FROM valid_pid p",
  "    JOIN individuals c ON p.child_fam68 = c.fam68 AND p.child_pn = c.pn",
  "    JOIN individuals f ON p.father_fam68 = f.fam68 AND p.father_pn = f.pn",
  "    JOIN individuals m ON p.mother_fam68 = m.fam68 AND p.mother_pn = m.pn",
  "),",
  "eligible AS (",
  "    SELECT * FROM linked",
  "    WHERE father_fam99 > 0 AND father_fam99 = mother_fam99",
  "      AND father_seq99 = 1 AND father_rel99 = 10",
  "      AND mother_seq99 BETWEEN 1 AND 20 AND mother_rel99 IN (20, 22)",
  "      AND child_fam23 > 0 AND child_seq23 BETWEEN 1 AND 20",
  "      AND child_rel23 IN (10, 20, 22)",
  "      AND (child_rel23 <> 10 OR child_seq23 = 1)",
  "      AND child_age23 BETWEEN 35 AND 49",
  "),",
  "parent_rows AS (",
  "    SELECT e.child_fam68, e.child_pn, 'father' AS parent_type,",
  "           f.head_income98 AS parent_income",
  "    FROM eligible e",
  "    JOIN family1999 f ON e.father_fam99 = f.fam99",
  "    UNION ALL",
  "    SELECT e.child_fam68, e.child_pn, 'mother' AS parent_type,",
  "           f.wife_income98 AS parent_income",
  "    FROM eligible e",
  "    JOIN family1999 f ON e.mother_fam99 = f.fam99",
  "),",
  "parent_sum AS (",
  "    SELECT child_fam68, child_pn,",
  "           SUM(parent_income) AS parent_income_1998,",
  "           COUNT(parent_income) AS n_valid_parent_incomes",
  "    FROM parent_rows",
  "    GROUP BY child_fam68, child_pn",
  "    HAVING COUNT(*) = 2 AND COUNT(parent_income) = 2",
  "),",
  "matched AS (",
  "    SELECT e.child_fam68, e.child_pn,",
  "           e.father_fam68, e.father_pn,",
  "           e.mother_fam68, e.mother_pn,",
  "           e.father_fam99 AS parent_family_1999,",
  "           e.child_fam99, e.child_fam23,",
  "           e.child_age99, e.child_age23,",
  "           e.father_age99, e.mother_age99,",
  "           e.child_rel23,",
  "           p.parent_income_1998,",
  "           CASE WHEN e.child_rel23 = 10 THEN f.rp_income22",
  "                WHEN e.child_rel23 IN (20, 22) THEN f.sp_income22",
  "           END AS child_income_2022",
  "    FROM eligible e",
  "    JOIN parent_sum p ON e.child_fam68 = p.child_fam68",
  "                     AND e.child_pn = p.child_pn",
  "    JOIN family2023 f ON e.child_fam23 = f.fam23",
  ")",
  "SELECT * FROM matched",
  "WHERE parent_income_1998 > 0 AND child_income_2022 > 0",
  "ORDER BY child_fam68, child_pn",
  "'''",
  "",
  "with sqlite3.connect(':memory:') as con:",
  "    pid.drop(columns=['PID1']).to_sql('pid', con, index=False)",
  "    ind.drop(columns=['ER30000']).to_sql('individuals', con, index=False)",
  "    f99[['fam99', 'head_income98', 'wife_income98']].to_sql('family1999', con, index=False)",
  "    f23[['fam23', 'rp_income22', 'sp_income22']].to_sql('family2023', con, index=False)",
  "    processed = pd.read_sql_query(query, con)",
  "",
  "if processed.duplicated(['child_fam68', 'child_pn']).any():",
  "    raise ValueError('SQL JOIN produced duplicate children')",
  "if processed.empty:",
  "    raise ValueError('No eligible biological parent-child pairs; review matching restrictions')",
  "Path(output_csv).parent.mkdir(parents=True, exist_ok=True)",
  "processed.to_csv(output_csv, index=False)",
  "print(f'Step 1 completed: {len(processed):,} adult-child observations.')",
  "print(f'Processed CSV: {output_csv}')"
), collapse = "\n")

reticulate::py_run_string(paste(python_paths, python_code, sep = "\n"), local = FALSE)