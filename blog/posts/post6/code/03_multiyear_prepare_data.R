# Blog 06 - Multi-year IGE data
# PSID surveys: 1999-2023; earnings: 1998-2022.
# R packages: install.packages(c("here", "reticulate"))
# Python package, if needed: reticulate::py_install("pandas")

if (!requireNamespace("here", quietly = TRUE)) stop("Install R package: here")
if (!requireNamespace("reticulate", quietly = TRUE)) stop("Install R package: reticulate")

raw_dir <- here::here("blog", "posts", "post6", "data", "raw")
out_dir <- here::here("blog", "posts", "post6", "data", "processed")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
if (!dir.exists(raw_dir)) stop("Missing data/raw; open your website .Rproj")

# Parent and child earnings come from separate survey windows.
parent_waves <- seq(1999L, 2011L, by = 2L)   # Parents: 1998-2010 incomes
child_waves <- seq(2013L, 2023L, by = 2L)    # Children: 2012-2022 incomes
min_parent_waves <- 3L
min_child_waves <- 3L

# Find the raw .txt files without relying on filename case.
find_psid_file <- function(filename) {
  files <- list.files(raw_dir, full.names = TRUE)
  found <- files[tolower(basename(files)) == tolower(filename)]
  if (length(found) != 1L) stop("Missing or ambiguous file in data/raw: ", filename)
  normalizePath(found, winslash = "/", mustWork = TRUE)
}
pid_path <- find_psid_file("PID23.txt")
ind_path <- find_psid_file("IND2023ER.txt")
family_files <- setNames(
  vapply(seq(1999L, 2023L, by = 2L), function(y) {
    find_psid_file(sprintf("FAM%dER.txt", y))
  }, character(1)), as.character(seq(1999L, 2023L, by = 2L))
)
for (path in c(pid_path, ind_path, family_files)) {
  layout <- sub("\\.txt$", ".do", path, ignore.case = TRUE)
  if (!file.exists(layout)) stop("Missing matching Stata .do layout: ", layout)
}

# File paths for Python.
py_literal <- function(x) encodeString(unname(x), quote = '"')
family_paths <- paste(
  sprintf("    %s: %s", py_literal(names(family_files)),
          vapply(family_files, py_literal, character(1))),
  collapse = ",\n"
)
python_paths <- paste0(
  "pid_path = ", py_literal(pid_path), "\n",
  "ind_path = ", py_literal(ind_path), "\n",
  "family_paths = {\n", family_paths, "\n}\n",
  "output_csv = ", py_literal(file.path(out_dir, "ige_multi_year.csv")), "\n",
  "PARENT_WAVES = [", paste(parent_waves, collapse = ", "), "]\n",
  "CHILD_WAVES = [", paste(child_waves, collapse = ", "), "]\n",
  "MIN_PARENT_WAVES = ", min_parent_waves, "\n",
  "MIN_CHILD_WAVES = ", min_child_waves
)

# Python processing code.
python_code <- paste(c(
  "import re",
  "import sqlite3",
  "from pathlib import Path",
  "import pandas as pd",
  "",
  "# Family file fields: interview ID, labor earnings, and business labor income",
  "# for the reference person and spouse.",
  "VARIABLES = {",
  "    1999: ('ER13002', 'ER16463', 'ER16490', 'ER16465', 'ER16511'),",
  "    2001: ('ER17002', 'ER20443', 'ER20422', 'ER20447', 'ER20444'),",
  "    2003: ('ER21002', 'ER24116', 'ER24109', 'ER24135', 'ER24111'),",
  "    2005: ('ER25002', 'ER27931', 'ER27910', 'ER27943', 'ER27940'),",
  "    2007: ('ER36002', 'ER40921', 'ER40900', 'ER40933', 'ER40930'),",
  "    2009: ('ER42002', 'ER46829', 'ER46808', 'ER46841', 'ER46838'),",
  "    2011: ('ER47302', 'ER52237', 'ER52216', 'ER52249', 'ER52246'),",
  "    2013: ('ER53002', 'ER58038', 'ER58017', 'ER58050', 'ER58047'),",
  "    2015: ('ER60002', 'ER65216', 'ER65197', 'ER65244', 'ER65225'),",
  "    2017: ('ER66002', 'ER71293', 'ER71274', 'ER71321', 'ER71302'),",
  "    2019: ('ER72002', 'ER77315', 'ER77296', 'ER77343', 'ER77324'),",
  "    2021: ('ER78002', 'ER81642', 'ER81623', 'ER81670', 'ER81651'),",
  "    2023: ('ER82002', 'ER85496', 'ER85477', 'ER85524', 'ER85505'),",
  "}",
  "",
  "# Wave-specific family ID, sequence number, and relationship fields.",
  "# Person keys: ER30001 and ER30002; 2023 age: ER35104.",
  "IND_WAVES = {",
  "    1999: ('ER33501', 'ER33502', 'ER33503'),",
  "    2001: ('ER33601', 'ER33602', 'ER33603'),",
  "    2003: ('ER33701', 'ER33702', 'ER33703'),",
  "    2005: ('ER33801', 'ER33802', 'ER33803'),",
  "    2007: ('ER33901', 'ER33902', 'ER33903'),",
  "    2009: ('ER34001', 'ER34002', 'ER34003'),",
  "    2011: ('ER34101', 'ER34102', 'ER34103'),",
  "    2013: ('ER34201', 'ER34202', 'ER34203'),",
  "    2015: ('ER34301', 'ER34302', 'ER34303'),",
  "    2017: ('ER34501', 'ER34502', 'ER34503'),",
  "    2019: ('ER34701', 'ER34702', 'ER34703'),",
  "    2021: ('ER34901', 'ER34902', 'ER34903'),",
  "    2023: ('ER35101', 'ER35102', 'ER35103'),",
  "}",
  "",
  "# BLS CPI-U, US city average, all items, annual average (not seasonally adjusted).",
  "# https://www.bls.gov/regions/northeast/data/consumerpriceindex_us_table.htm",
  "CPI_U = {1998: 163.0, 2000: 172.2, 2002: 179.9, 2004: 188.9,",
  "         2006: 201.6, 2008: 215.303, 2010: 218.056, 2012: 229.594,",
  "         2014: 236.736, 2016: 240.007, 2018: 251.107,",
  "         2020: 258.811, 2022: 292.655}",
  "",
  "",
  "def read_psid(filename, wanted):",
  "    # Column offsets come from the matching Stata layout file.",
  "    path = Path(filename)",
  "    layout = path.with_suffix('.do')",
  "    if not path.is_file() or not layout.is_file():",
  "        raise FileNotFoundError(f'Need {path.name} and {layout.name} in data/raw')",
  "    print(f'Reading {path.name} ...', flush=True)",
  "    do = layout.read_text(encoding='utf-8-sig', errors='replace')",
  "    do = re.sub(r'/\\*.*?\\*/', ' ', do, flags=re.S)",
  "    match = re.search(r'\\binfix\\b(.*?)\\busing\\b', do, flags=re.I | re.S)",
  "    if match is None:",
  "        raise ValueError(f'Could not find infix layout in {layout.name}')",
  "    positions = {",
  "        name.upper(): (int(start) - 1, int(end or start))",
  "        for name, start, end in re.findall(",
  "            r'\\b([A-Za-z][A-Za-z0-9_]*)\\s+(\\d+)\\s*(?:-\\s*(\\d+))?\\b',",
  "            match.group(1))",
  "    }",
  "    missing = sorted(set(wanted).difference(positions))",
  "    if missing:",
  "        raise ValueError(f'{layout.name} lacks variable positions: {missing}')",
  "    result = {name: [] for name in wanted}",
  "    with path.open('rb') as stream:",
  "        for line in stream:",
  "            if not line.strip():",
  "                continue",
  "            for name in wanted:",
  "                start, stop = positions[name]",
  "                result[name].append(line[start:stop].strip().decode('ascii', 'replace'))",
  "    data = pd.DataFrame(result)",
  "    for name in wanted:",
  "        data[name] = pd.to_numeric(data[name], errors='coerce')",
  "    return data",
  "",
  "",
  "def check_unique(frame, columns, title):",
  "    if frame.duplicated(columns).any():",
  "        raise ValueError(f'Duplicate identifiers in {title}: {columns}')",
  "",
  "",
  "# Read parent identifiers and individual histories.",
  "pid_fields = ['PID1', 'PID2', 'PID3', 'PID4', 'PID5', 'PID23', 'PID24']",
  "ind_fields = ['ER30000', 'ER30001', 'ER30002', 'ER35104']",
  "for spec in IND_WAVES.values():",
  "    ind_fields.extend(spec)",
  "pid = read_psid(pid_path, pid_fields)",
  "ind = read_psid(ind_path, ind_fields)",
  "if (pid['PID1'].nunique() != 1 or ind['ER30000'].nunique() != 1 or",
  "        pid['PID1'].iloc[0] != ind['ER30000'].iloc[0]):",
  "    raise ValueError('PID23 and IND2023ER release numbers differ')",
  "",
  "pid = pid.rename(columns={",
  "    'PID2': 'child_fam68', 'PID3': 'child_pn',",
  "    'PID4': 'mother_fam68', 'PID5': 'mother_pn',",
  "    'PID23': 'father_fam68', 'PID24': 'father_pn',",
  "})",
  "ind = ind.rename(columns={",
  "    'ER30001': 'fam68', 'ER30002': 'pn', 'ER35104': 'age23',",
  "    'ER33501': 'fam99', 'ER33502': 'seq99', 'ER33503': 'rel99',",
  "    'ER35101': 'fam23', 'ER35102': 'seq23', 'ER35103': 'rel23',",
  "})",
  "check_unique(pid, ['child_fam68', 'child_pn'], 'PID23')",
  "check_unique(ind, ['fam68', 'pn'], 'IND2023ER')",
  "",
  "# Use the same anchor sample as the single-year analysis:",
  "# father as Head and mother as Wife in 1999;",
  "# child as reference person or spouse/partner, age 35-49, in 2023.",
  "CANDIDATES_SQL = '''",
  "SELECT p.child_fam68, p.child_pn,",
  "       p.father_fam68, p.father_pn, p.mother_fam68, p.mother_pn,",
  "       f.fam99 AS parent_family_1999,",
  "       f.age23 AS father_age23, m.age23 AS mother_age23,",
  "       c.age23 AS child_age23",
  "FROM pid p",
  "JOIN individuals c ON p.child_fam68 = c.fam68 AND p.child_pn = c.pn",
  "JOIN individuals f ON p.father_fam68 = f.fam68 AND p.father_pn = f.pn",
  "JOIN individuals m ON p.mother_fam68 = m.fam68 AND p.mother_pn = m.pn",
  "WHERE p.child_fam68 > 0 AND p.child_pn BETWEEN 1 AND 399",
  "  AND p.father_fam68 > 0 AND p.father_pn BETWEEN 1 AND 399",
  "  AND p.mother_fam68 > 0 AND p.mother_pn BETWEEN 1 AND 399",
  "  AND NOT (p.father_fam68 = p.mother_fam68 AND p.father_pn = p.mother_pn)",
  "  AND f.fam99 > 0 AND f.fam99 = m.fam99",
  "  AND f.seq99 = 1 AND f.rel99 = 10",
  "  AND m.seq99 BETWEEN 1 AND 20 AND m.rel99 IN (20, 22)",
  "  AND c.fam23 > 0 AND c.seq23 BETWEEN 1 AND 20",
  "  AND c.rel23 IN (10, 20, 22)",
  "  AND (c.rel23 <> 10 OR c.seq23 = 1)",
  "  AND c.age23 BETWEEN 35 AND 49",
  "'''",
  "with sqlite3.connect(':memory:') as con:",
  "    pid[['child_fam68', 'child_pn', 'father_fam68', 'father_pn',",
  "         'mother_fam68', 'mother_pn']].to_sql('pid', con, index=False)",
  "    ind[['fam68', 'pn', 'age23', 'fam99', 'seq99', 'rel99',",
  "         'fam23', 'seq23', 'rel23']].to_sql('individuals', con, index=False)",
  "    con.execute('CREATE UNIQUE INDEX idx_ind_key ON individuals(fam68, pn)')",
  "    candidates = pd.read_sql_query(CANDIDATES_SQL, con)",
  "",
  "if candidates.empty:",
  "    raise ValueError('No parent-child candidates under the 1999/2023 anchor restrictions')",
  "check_unique(candidates, ['child_fam68', 'child_pn'], 'candidate match')",
  "print(f'Biologically matched candidates: {len(candidates):,}', flush=True)",
  "",
  "# Keep the survey histories of the matched people.",
  "parent_ids = pd.concat([",
  "    candidates[['father_fam68', 'father_pn']].set_axis(['fam68', 'pn'], axis=1),",
  "    candidates[['mother_fam68', 'mother_pn']].set_axis(['fam68', 'pn'], axis=1),",
  "    candidates[['child_fam68', 'child_pn']].set_axis(['fam68', 'pn'], axis=1),",
  "], ignore_index=True).drop_duplicates()",
  "ind_matches = ind.merge(parent_ids, on=['fam68', 'pn'], how='inner', validate='one_to_one')",
  "wave_frames = []",
  "for year, (fam_col, seq_col, rel_col) in IND_WAVES.items():",
  "    # The anchor-year ID columns have already been renamed.",
  "    if year == 1999:",
  "        fam_col, seq_col, rel_col = 'fam99', 'seq99', 'rel99'",
  "    if year == 2023:",
  "        fam_col, seq_col, rel_col = 'fam23', 'seq23', 'rel23'",
  "    wave = ind_matches[['fam68', 'pn', fam_col, seq_col, rel_col]].copy()",
  "    wave.columns = ['fam68', 'pn', 'fam', 'seq', 'rel']",
  "    wave['survey_year'] = year",
  "    wave_frames.append(wave[['fam68', 'pn', 'survey_year', 'fam', 'seq', 'rel']])",
  "individual_waves = pd.concat(wave_frames, ignore_index=True)",
  "",
  "# Construct individual earnings for each family survey wave.",
  "# Add labor earnings and the labor component of business income.",
  "# Farm income is excluded; use each person's own income.",
  "family_frames = []",
  "for year, spec in VARIABLES.items():",
  "    fam_id, rp_labor, rp_business, sp_labor, sp_business = spec",
  "    frame = read_psid(family_paths[str(year)], list(spec))",
  "    check_unique(frame, [fam_id], f'FAM{year}ER')",
  "",
  "    # Income-code cutoffs differ across survey years.",
  "    # Values at or above the selected cutoff are set to missing.",
  "    if year <= 2009:",
  "        ceiling = {rp_labor: 9999999, sp_labor: 9999999,",
  "                   rp_business: (999999 if year <= 2003 else 9999999),",
  "                   sp_business: (999999 if year <= 2003 else 9999999)}",
  "        if year == 1999:",
  "            ceiling[sp_labor] = 9999997",
  "    else:",
  "        ceiling = {v: 9999998 for v in (rp_labor, rp_business, sp_labor, sp_business)}",
  "    for v, limit in ceiling.items():",
  "        frame.loc[(frame[v] < 0) | (frame[v] >= limit), v] = float('nan')",
  "",
  "    # A missing component leaves that person-year income missing.",
  "    frame['rp_income'] = frame[rp_labor] + frame[rp_business]",
  "    frame['sp_income'] = frame[sp_labor] + frame[sp_business]",
  "    wave = frame[[fam_id, 'rp_income', 'sp_income']].copy()",
  "    wave.columns = ['fam', 'rp_income', 'sp_income']",
  "    wave['survey_year'] = year",
  "    family_frames.append(wave[['survey_year', 'fam', 'rp_income', 'sp_income']])",
  "family_waves = pd.concat(family_frames, ignore_index=True)",
  "check_unique(family_waves, ['survey_year', 'fam'], 'family wave stack')",
  "",
  "# Calculate wave averages after converting earnings to 2022 dollars.",
  "# Both parents must be in the same family unit in an eligible wave.",
  "# Include recorded zero earnings; exclude missing earnings.",
  "parent_years = ', '.join(map(str, PARENT_WAVES))",
  "child_years = ', '.join(map(str, CHILD_WAVES))",
  "query = f'''",
  "WITH parent_roles AS (",
  "  SELECT c.child_fam68, c.child_pn, pf.survey_year,",
  "         CASE WHEN pf.rel = 10 AND pm.rel IN (20,22) AND pf.seq = 1",
  "                 THEN fw.rp_income",
  "              WHEN pm.rel = 10 AND pf.rel IN (20,22) AND pm.seq = 1",
  "                 THEN fw.sp_income END AS father_income,",
  "         CASE WHEN pm.rel = 10 AND pf.rel IN (20,22) AND pm.seq = 1",
  "                 THEN fw.rp_income",
  "              WHEN pf.rel = 10 AND pm.rel IN (20,22) AND pf.seq = 1",
  "                 THEN fw.sp_income END AS mother_income",
  "  FROM candidates c",
  "  JOIN person_waves pf ON pf.fam68 = c.father_fam68",
  "                      AND pf.pn = c.father_pn",
  "  JOIN person_waves pm ON pm.fam68 = c.mother_fam68",
  "                      AND pm.pn = c.mother_pn",
  "                      AND pm.survey_year = pf.survey_year AND pm.fam = pf.fam",
  "  JOIN family_waves fw ON fw.survey_year = pf.survey_year AND fw.fam = pf.fam",
  "  WHERE pf.survey_year IN ({parent_years})",
  "    AND pf.fam > 0 AND pf.seq BETWEEN 1 AND 20 AND pm.seq BETWEEN 1 AND 20",
  "),",
  "parent_income AS (",
  "  SELECT child_fam68, child_pn, survey_year,",
  "         father_income + mother_income AS annual_parent_income",
  "  FROM parent_roles",
  "  WHERE father_income >= 0 AND mother_income >= 0",
  "),",
  "parent_avg AS (",
  "  SELECT p.child_fam68, p.child_pn,",
  "         COUNT(*) AS n_parent_years,",
  "         AVG(p.annual_parent_income * {CPI_U[2022]} / c.cpi) AS parent_avg_2022usd,",
  "         MAX(CASE WHEN p.survey_year = 1999 THEN p.annual_parent_income END)",
  "             AS parent_income_1998",
  "  FROM parent_income p",
  "  JOIN cpi c ON c.income_year = p.survey_year - 1",
  "  GROUP BY p.child_fam68, p.child_pn",
  "),",
  "child_roles AS (",
  "  SELECT c.child_fam68, c.child_pn, cw.survey_year,",
  "         CASE WHEN cw.rel = 10 AND cw.seq = 1 THEN fw.rp_income",
  "              WHEN cw.rel IN (20,22) AND cw.seq BETWEEN 1 AND 20",
  "                   THEN fw.sp_income END AS annual_child_income",
  "  FROM candidates c",
  "  JOIN person_waves cw ON cw.fam68 = c.child_fam68 AND cw.pn = c.child_pn",
  "  JOIN family_waves fw ON fw.survey_year = cw.survey_year AND fw.fam = cw.fam",
  "  WHERE cw.survey_year IN ({child_years}) AND cw.fam > 0",
  "),",
  "child_avg AS (",
  "  SELECT c.child_fam68, c.child_pn,",
  "         COUNT(*) AS n_child_years,",
  "         AVG(c.annual_child_income * {CPI_U[2022]} / x.cpi) AS child_avg_2022usd,",
  "         MAX(CASE WHEN c.survey_year = 2023 THEN c.annual_child_income END)",
  "             AS child_income_2022",
  "  FROM child_roles c",
  "  JOIN cpi x ON x.income_year = c.survey_year - 1",
  "  WHERE c.annual_child_income >= 0",
  "  GROUP BY c.child_fam68, c.child_pn",
  ")",
  "SELECT e.child_fam68, e.child_pn, e.father_fam68, e.father_pn,",
  "       e.mother_fam68, e.mother_pn, e.parent_family_1999, e.child_age23,",
  "       p.parent_income_1998, k.child_income_2022,",
  "       p.parent_avg_2022usd, k.child_avg_2022usd,",
  "       p.n_parent_years, k.n_child_years",
  "FROM candidates e",
  "JOIN parent_avg p ON p.child_fam68 = e.child_fam68 AND p.child_pn = e.child_pn",
  "JOIN child_avg k ON k.child_fam68 = e.child_fam68 AND k.child_pn = e.child_pn",
  "WHERE p.n_parent_years >= {MIN_PARENT_WAVES}",
  "  AND k.n_child_years >= {MIN_CHILD_WAVES}",
  "  AND p.parent_income_1998 > 0 AND k.child_income_2022 > 0",
  "  AND p.parent_avg_2022usd > 0 AND k.child_avg_2022usd > 0",
  "ORDER BY e.child_fam68, e.child_pn",
  "'''",
  "",
  "with sqlite3.connect(':memory:') as con:",
  "    candidates.to_sql('candidates', con, index=False)",
  "    individual_waves.to_sql('person_waves', con, index=False)",
  "    family_waves.to_sql('family_waves', con, index=False)",
  "    cpi = pd.DataFrame({'income_year': list(CPI_U), 'cpi': list(CPI_U.values())})",
  "    cpi.to_sql('cpi', con, index=False)",
  "    con.execute('CREATE INDEX idx_pwave ON person_waves(fam68, pn, survey_year)')",
  "    con.execute('CREATE UNIQUE INDEX idx_fwave ON family_waves(survey_year, fam)')",
  "    processed = pd.read_sql_query(query, con)",
  "",
  "check_unique(processed, ['child_fam68', 'child_pn'], 'multiyear processed')",
  "if processed.empty:",
  "    raise ValueError('No common-sample matches; review income waves and minimum observations')",
  "Path(output_csv).parent.mkdir(parents=True, exist_ok=True)",
  "processed.to_csv(output_csv, index=False)",
  "print(f'Multi-year IGE: {len(processed):,} children in the common sample.', flush=True)",
  "print(f'Parents: {PARENT_WAVES}; children: {CHILD_WAVES}.', flush=True)",
  "print(f'Output: {output_csv}', flush=True)"
), collapse = "\n")

reticulate::py_run_string(paste(python_paths, python_code, sep = "\n"), local = FALSE)
